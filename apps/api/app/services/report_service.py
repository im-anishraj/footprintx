"""Report generation service (PDF and Markdown)."""
from __future__ import annotations

import io
from datetime import datetime, timezone
from typing import Any


def mask_email(email: str) -> str:
    """Mask an email: show first 2 chars + ***@domain."""
    if "@" not in email:
        return "***"
    local, domain = email.rsplit("@", 1)
    if len(local) <= 2:
        masked_local = local[0] + "***" if local else "***"
    else:
        masked_local = local[:2] + "***"
    return f"{masked_local}@{domain}"


def _build_findings_text(results: dict[str, Any]) -> str:
    """Build plain-text findings list."""
    lines = []
    findings = results.get("findings", [])
    if not findings:
        lines.append("No accounts detected by these checks. That isn't a guarantee.\n")
        return "\n".join(lines)

    for f in findings:
        status_icon = {
            "indicator_found": "[!]",
            "likely": "[?]",
            "not_detected": "[ ]",
            "unknown": "[~]",
            "rate_limited": "[R]",
            "unable_to_verify": "[E]",
            "skipped": "[-]",
        }.get(f.get("status", "unknown"), "[?]")

        lines.append(f'{status_icon} {f.get("service_name", "Unknown")} — {f.get("status_label", f.get("status", "unknown"))}')
        if f.get("explanation"):
            lines.append(f'    {f["explanation"]}')
        if f.get("confidence"):
            lines.append(f'    Confidence: {f["confidence"]}')
        lines.append("")

    return "\n".join(lines)


def _build_breaches_text(results: dict[str, Any]) -> str:
    """Build plain-text breaches list."""
    lines = []
    breaches = results.get("breaches", [])
    if not breaches:
        lines.append("No known breaches found for this email.\n")
        return "\n".join(lines)

    for b in breaches:
        lines.append(f'• {b.get("name", "Unknown")} (breach date: {b.get("date", "unknown")})')
        data_classes = b.get("data_classes", [])
        if data_classes:
            lines.append(f'  Exposed data: {", ".join(data_classes)}')
        lines.append("")

    return "\n".join(lines)


def _build_actions_text(results: dict[str, Any]) -> str:
    """Build plain-text action plan."""
    lines = []
    actions = results.get("actions", {})

    for priority, label in [("today", "Today"), ("this_week", "This Week"), ("this_month", "This Month")]:
        items = actions.get(priority, [])
        if items:
            lines.append(f"\n### {label}")
            for item in items:
                lines.append(f'- [ ] {item.get("action", "")}')
                if item.get("guide_id"):
                    lines.append(f'      Guide: {item.get("guide_title", item["guide_id"])}')
            lines.append("")

    if not any(actions.get(p) for p in ["today", "this_week", "this_month"]):
        lines.append("No specific actions recommended at this time.\n")

    return "\n".join(lines)


def generate_markdown_report(
    results: dict[str, Any],
    masked_email: str,
) -> str:
    """Generate a Markdown report."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    coverage = results.get("coverage", {})
    coverage_text = f'{coverage.get("done", 0)} of {coverage.get("total", 0)} checks completed'

    md = f"""# FootprintX — Digital Footprint Report

**Email**: {masked_email}
**Generated**: {now}
**Coverage**: {coverage_text}

---

## Account Indicators

{_build_findings_text(results)}

---

## Data Breach Exposure

{_build_breaches_text(results)}

*Breach data provided by [Have I Been Pwned](https://haveibeenpwned.com).*

---

## Recommended Actions

{_build_actions_text(results)}

---

## About This Report

This report was generated by [FootprintX](https://github.com/footprintx/footprintx), an open-source digital footprint auditing tool.

**Important disclaimers:**
- Results are *indicators*, not proof. A detected account may be associated with this email address but cannot be confirmed as active.
- \"Not detected\" does not guarantee an account doesn't exist — only that our checks didn't find one.
- This report is generated on demand and is not stored after download.
- For ongoing breach monitoring, visit [Have I Been Pwned](https://haveibeenpwned.com).

---

*FootprintX — Know your footprint. Clean it up.*
"""
    return md


def generate_pdf_report(
    results: dict[str, Any],
    masked_email: str,
) -> bytes:
    """Generate a PDF report using WeasyPrint."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    coverage = results.get("coverage", {})
    coverage_text = f'{coverage.get("done", 0)} of {coverage.get("total", 0)} checks completed'

    findings_html = ""
    for f in results.get("findings", []):
        status = f.get("status", "unknown")
        status_colors = {
            "indicator_found": "#B45309",
            "likely": "#B45309",
            "not_detected": "#15803D",
            "unknown": "#475569",
            "rate_limited": "#475569",
            "unable_to_verify": "#475569",
            "skipped": "#475569",
        }
        color = status_colors.get(status, "#475569")
        label = f.get("status_label", status.replace("_", " ").title())
        findings_html += f"""
        <div style="border:1px solid #E2E8F0; border-radius:8px; padding:12px; margin-bottom:8px;">
          <div style="display:flex; justify-content:space-between; align-items:center;">
            <strong>{f.get("service_name", "Unknown")}</strong>
            <span style="color:{color}; font-size:13px; font-weight:600;">{label}</span>
          </div>
          <div style="color:#475569; font-size:13px; margin-top:4px;">{f.get("explanation", "")}</div>
          <div style="color:#94A3B8; font-size:12px; margin-top:2px;">Confidence: {f.get("confidence", "—")} · Category: {f.get("category", "—")}</div>
        </div>"""

    if not results.get("findings"):
        findings_html = '<p style="color:#475569;">No accounts detected by these checks. That isn\'t a guarantee.</p>'

    breaches_html = ""
    for b in results.get("breaches", []):
        data_classes = ", ".join(b.get("data_classes", []))
        breaches_html += f"""
        <div style="border:1px solid #E2E8F0; border-radius:8px; padding:12px; margin-bottom:8px;">
          <strong>{b.get("name", "Unknown")}</strong>
          <span style="color:#475569; font-size:13px;"> — {b.get("date", "unknown")}</span>
          <div style="color:#475569; font-size:13px; margin-top:4px;">Exposed: {data_classes}</div>
        </div>"""

    if not results.get("breaches"):
        breaches_html = '<p style="color:#475569;">No known breaches found for this email.</p>'

    actions_html = ""
    for priority, label in [("today", "Today"), ("this_week", "This Week"), ("this_month", "This Month")]:
        items = results.get("actions", {}).get(priority, [])
        if items:
            actions_html += f'<h3 style="color:#0F172A; margin-top:16px;">{label}</h3><ul>'
            for item in items:
                actions_html += f'<li>{item.get("action", "")}</li>'
            actions_html += "</ul>"

    html = f"""<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<style>
  @page {{ size: A4; margin: 2cm; }}
  body {{ font-family: Inter, system-ui, -apple-system, sans-serif; color: #0F172A; font-size: 14px; line-height: 1.6; }}
  h1 {{ color: #4F46E5; font-size: 24px; margin-bottom: 4px; }}
  h2 {{ color: #0F172A; font-size: 18px; border-bottom: 2px solid #E2E8F0; padding-bottom: 8px; margin-top: 28px; }}
  .meta {{ color: #475569; font-size: 13px; margin-bottom: 20px; }}
  .footer {{ margin-top: 32px; padding-top: 16px; border-top: 1px solid #E2E8F0; color: #94A3B8; font-size: 11px; }}
  .attribution {{ color: #475569; font-size: 12px; font-style: italic; margin-top: 8px; }}
</style>
</head>
<body>
  <h1>FootprintX</h1>
  <p class="meta">Digital Footprint Report · {masked_email} · {now} · {coverage_text}</p>

  <h2>Account Indicators</h2>
  {findings_html}

  <h2>Data Breach Exposure</h2>
  {breaches_html}
  <p class="attribution">Breach data provided by Have I Been Pwned (haveibeenpwned.com).</p>

  <h2>Recommended Actions</h2>
  {actions_html if actions_html else '<p style="color:#475569;">No specific actions recommended at this time.</p>'}

  <div class="footer">
    <p>This report was generated by FootprintX, an open-source digital footprint auditing tool.</p>
    <p><strong>Disclaimer:</strong> Results are indicators, not proof. "Not detected" does not guarantee absence. Generated on demand, not stored after download.</p>
    <p>FootprintX — Know your footprint. Clean it up.</p>
  </div>
</body>
</html>"""

    try:
        from weasyprint import HTML
        pdf_bytes = HTML(string=html).write_pdf()
        return pdf_bytes
    except ImportError:
        # Fallback: return HTML as bytes for environments without WeasyPrint
        return html.encode("utf-8")
